@contextmanager
def _default_utf8_open():
    """Ensure open() defaults to UTF-8 on Windows (cp932 locale) for third-party libraries."""
    orig_open = builtins.open
    def _utf8_open(file, mode='r', buffering=-1, encoding=None, *args, **kwargs):
        if 'b' not in mode and encoding is None:
            encoding = 'utf-8'
        return orig_open(file, mode, buffering, encoding, *args, **kwargs)
    builtins.open = _utf8_open
    try:
        yield
    finally:
        builtins.open = orig_open


## TTS Audio Generation
# Class for generating a cache of the audio file on disk for Ukrainian Ground Truth and Japanese Candidates.
class AudioGenerator:
    """
    Dual-language Neural TTS synthesizer:
    - Ukrainian Ground Truth: ESPnet2 VITS (`ukrainian-tts`, Voices.Dmytro, Stress.Model)
    - Japanese Candidates: Kokoro-82M Neural ONNX (`kokoro-v1.0.fp16.onnx`, voice `jm_kumo`),
      conditioned directly on phonetic IPA sequences generated by `JapaneseG2P` to preserve
      both standard Katakana and Ukrainian-specific extended Katakana digraphs.
    """

    KOKORO_MODEL_URLS = {
        'kokoro-v1.0.fp16.onnx': 'https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.fp16.onnx',
        'voices-v1.0.bin': 'https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin',
        'config.json': 'https://huggingface.co/hexgrad/Kokoro-82M/resolve/main/config.json',
    }
    TARGET_SR = 16000
    KOKORO_SR = 24000

    def __init__(self, base_audio_dir: str = 'audio', japanese_voice: str = 'jm_kumo'):
        self.base_dir = base_audio_dir
        self.japanese_voice = japanese_voice
        os.makedirs(f'{self.base_dir}/ukrainian_ground_truth', exist_ok=True)
        os.makedirs(f'{self.base_dir}/japanese_candidates', exist_ok=True)

        # Initialize Ukrainian TTS (when available in environment)
        self.ukrainian_tts = None
        self.ukrainian_voice = None
        self.ukrainian_stress = None
        if TTS is not None:
            device = 'cuda' if (torch is not None and torch.cuda.is_available()) else 'cpu'
            with _default_utf8_open():
                self.ukrainian_tts = TTS(device=device)
            self.ukrainian_voice = Voices.Dmytro.value
            self.ukrainian_stress = Stress.Model.value

        # Initialize Japanese G2P and Kokoro-82M Neural ONNX synthesizer
        self.japanese_g2p = JapaneseG2P()
        self._init_kokoro_onnx()

    def _init_kokoro_onnx(self):
        model_dir = os.path.join(self.base_dir, '_kokoro_model')
        alt_cache_dir = os.path.join(self.base_dir, 'tts_comparison', '_model_cache')
        os.makedirs(model_dir, exist_ok=True)

        resolved_paths = {}
        for fname, url in self.KOKORO_MODEL_URLS.items():
            primary_path = os.path.join(model_dir, fname)
            alt_path = os.path.join(alt_cache_dir, fname)
            if os.path.exists(primary_path) and os.path.getsize(primary_path) > 100:
                resolved_paths[fname] = primary_path
            elif os.path.exists(alt_path) and os.path.getsize(alt_path) > 100:
                resolved_paths[fname] = alt_path
            else:
                tmp_path = primary_path + '.tmp'
                print(f'Downloading Kokoro ONNX resource {fname} ...')
                urllib.request.urlretrieve(url, tmp_path)
                os.replace(tmp_path, primary_path)
                resolved_paths[fname] = primary_path

        with open(resolved_paths['config.json'], 'r', encoding='utf-8') as f:
            self.kokoro_vocab = json.load(f)['vocab']
        self.kokoro_voices = np.load(resolved_paths['voices-v1.0.bin'])

        providers = ['CUDAExecutionProvider', 'CPUExecutionProvider']
        available = ort.get_available_providers()
        active_providers = [p for p in providers if p in available] or ['CPUExecutionProvider']
        sess_opts = ort.SessionOptions()
        cpu_quota = len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else (os.cpu_count() or 2)
        sess_opts.intra_op_num_threads = max(1, min(4, int(os.environ.get('SLURM_CPUS_PER_TASK') or cpu_quota)))
        sess_opts.inter_op_num_threads = 1
        self.kokoro_sess = ort.InferenceSession(
            resolved_paths['kokoro-v1.0.fp16.onnx'],
            sess_options=sess_opts,
            providers=active_providers
        )
        self.kokoro_input_names = [inp.name for inp in self.kokoro_sess.get_inputs()]

    @staticmethod
    def _is_empty(text) -> bool:
        if text is None or (isinstance(text, float) and math.isnan(text)):
            return True
        return not str(text).strip()

    @staticmethod
    def _is_valid_wav(path: str) -> bool:
        return os.path.exists(path) and os.path.getsize(path) > 44

    @staticmethod
    def _text_hash_ua(text: str) -> str:
        return hashlib.md5(f"v2:{text}".encode('utf-8')).hexdigest()[:8]

    def _text_hash_ja(self, text: str) -> str:
        return hashlib.md5(f"v3_kokoro_{self.japanese_voice}:{text}".encode('utf-8')).hexdigest()[:8]

    def _g2p_to_kokoro_ipa(self, kana_text: str) -> str:
        """
        Convert Katakana string into Kokoro-82M single-character IPA representation
        via JapaneseG2P, preserving extended Ukrainian-specific digraph distinctions.
        """
        raw_ipa = self.japanese_g2p.convert(kana_text)
        ipa = (
            raw_ipa.replace('t͡ɕ', 'ʨ')
            .replace('d͡ʑ', 'ʥ')
            .replace('t͡s', 'ʦ')
            .replace('d͡z', 'ʣ')
            .replace('g', 'ɡ')
            .replace('ʦʲ', 'ʦj')
            .replace('ʣʲ', 'ʣj')
            .replace('sʲ', 'sj')
            .replace('zʲ', 'zj')
            .replace('nn', 'ɴn')
            .replace('mm', 'ɴm')
            .replace('sɯ', 'sɨ')
            .replace('zɯ', 'zɨ')
            .replace('ʦɯ', 'ʦɨ')
            .replace('ʨɯ', 'ʨɨ')
            .replace('ʥɯ', 'ʥɨ')
            .replace('ɕɯ', 'ɕɨ')
            .replace('ʲɯ', 'ʲɨ')
            .replace('w', 'β')
        )
        return ipa

    def _synthesize_japanese_kana(self, kana_text: str):
        ipa_str = self._g2p_to_kokoro_ipa(kana_text)
        token_ids = [self.kokoro_vocab[ch] for ch in ipa_str if ch in self.kokoro_vocab]
        if not token_ids:
            return np.zeros(self.TARGET_SR // 2, dtype=np.int16), self.TARGET_SR

        tokens = np.array([[0] + token_ids + [0]], dtype=np.int64)
        style_idx = min(len(token_ids), self.kokoro_voices[self.japanese_voice].shape[0] - 1)
        style = self.kokoro_voices[self.japanese_voice][style_idx].astype(np.float32)
        speed = np.array([1.0], dtype=np.float32)

        audio_24k = self.kokoro_sess.run(
            None,
            {
                self.kokoro_input_names[0]: tokens,
                self.kokoro_input_names[1]: style,
                self.kokoro_input_names[2]: speed,
            },
        )[0]
        audio_f32 = np.squeeze(audio_24k).astype(np.float32)

        # Resample 24 kHz -> 16 kHz for WavLM-Base-Plus compatibility
        g = math.gcd(self.KOKORO_SR, self.TARGET_SR)
        audio_16k = resample_poly(audio_f32, self.TARGET_SR // g, self.KOKORO_SR // g)

        peak = np.max(np.abs(audio_16k))
        if peak > 0:
            audio_16k = (audio_16k / peak) * 0.85
        pcm16 = np.clip(audio_16k * 32767.0, -32768, 32767).astype(np.int16)
        return pcm16, self.TARGET_SR

    # Generating Ukrainian TTS data
    def generate_ukrainian(self, text_with_accent: str, uid: str) -> str:
        if self._is_empty(text_with_accent):
            return ''
        clean_text = str(text_with_accent).strip()
        thash = self._text_hash_ua(clean_text)
        output_path = f'{self.base_dir}/ukrainian_ground_truth/{uid}_{thash}.wav'
        if not self._is_valid_wav(output_path):
            if self.ukrainian_tts is None:
                raise RuntimeError("ukrainian-tts is not installed in the current Python environment.")
            tmp_path = output_path + '.tmp.wav'
            with _default_utf8_open(), open(tmp_path, 'wb') as f:
                self.ukrainian_tts.tts(
                    text=clean_text,
                    voice=self.ukrainian_voice,
                    stress=self.ukrainian_stress,
                    output_fp=f
                )
            os.replace(tmp_path, output_path)
        return output_path

    # Generating Japanese TTS data
    def generate_japanese(self, kana_text: str, uid: str, method_name: str) -> str:
        if self._is_empty(kana_text):
            return ''
        clean_kana = str(kana_text).strip()
        thash = self._text_hash_ja(clean_kana)
        output_path = f'{self.base_dir}/japanese_candidates/{uid}_{method_name}_{thash}.wav'
        if not self._is_valid_wav(output_path):
            pcm16, sr = self._synthesize_japanese_kana(clean_kana)
            tmp_path = output_path + '.tmp.wav'
            scipy.io.wavfile.write(tmp_path, sr, pcm16)
            os.replace(tmp_path, output_path)
        return output_path


